// Build output must never silently acquire an unclassified page.
const build = await read("scripts/build.js");
const roots = [
  ...build
    .match(/const htmlFiles = \[([\s\S]*?)\];/)[1]
    .matchAll(/'([^']+\.html)'/g),
].map((x) => x[1]);
async function walk(dir) {
  for (const e of await readdir(resolve(root, dir), {
    withFileTypes: true,
  }).catch(() => [])) {
    const p = dir + "/" + e.name;
    if (e.isDirectory()) await walk(p);
    else if (p.endsWith(".html")) roots.push(p);
  }
}
